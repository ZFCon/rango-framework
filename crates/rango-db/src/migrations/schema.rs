//! Schema editor: DDL generation for SQLite and PostgreSQL (`db.backends.*.schema`).

use rango_core::exceptions::{Error, Result};
use rango_core::utils::crypto::HashAlgorithm;

use crate::backends::Vendor;
use crate::models::meta::{Constraint, Default_, Field, FieldType, ModelMeta, Registry};
use crate::value::Value;

/// `names_digest(*args, length)`: md5 hex prefix used in generated index/constraint names.
pub fn names_digest(args: &[&str], length: usize) -> String {
    let mut data = Vec::new();
    for a in args {
        data.extend_from_slice(a.as_bytes());
    }
    let hex: String = HashAlgorithm::Md5.digest(&data).iter().map(|b| format!("{b:02x}")).collect();
    hex[..length].to_owned()
}

/// `_create_index_name(table, columns, suffix)`.
pub fn index_name(vendor: Vendor, table: &str, columns: &[&str], suffix: &str) -> String {
    let max = match vendor {
        Vendor::Postgresql => 63,
        Vendor::Sqlite => 200,
    };
    let mut hash = format!("{}{suffix}", names_digest(&std::iter::once(table).chain(columns.iter().copied()).collect::<Vec<_>>(), 8));
    let joined = columns.join("_");
    let name = format!("{table}_{joined}_{hash}");
    if name.len() <= max {
        return name;
    }
    if hash.len() > max / 3 {
        hash.truncate(max / 3);
    }
    let other = (max - hash.len()) / 2 - 1;
    format!("{}_{}_{hash}", &table[..other.min(table.len())], &joined[..other.min(joined.len())])
}

/// Statements produced for one operation (`collect_sql=True`).
#[derive(Default, Debug, Clone)]
pub struct Sql(pub Vec<String>);

pub struct SchemaEditor<'a> {
    pub vendor: Vendor,
    pub registry: &'a Registry,
    pub sql: Sql,
    /// Statements the reference implementation defers until the end (FK constraints on PostgreSQL, indexes).
    deferred: Vec<String>,
}

fn q(v: Vendor, n: &str) -> String {
    v.quote(n)
}

impl<'a> SchemaEditor<'a> {
    pub fn new(vendor: Vendor, registry: &'a Registry) -> Self {
        SchemaEditor { vendor, registry, sql: Sql::default(), deferred: Vec::new() }
    }

    fn emit(&mut self, s: String) {
        self.sql.0.push(s);
    }

    /// Hand deferred statements to the next operation's editor (the reference implementation keeps one editor per migration).
    pub fn take_deferred(&mut self) -> Vec<String> {
        std::mem::take(&mut self.deferred)
    }

    pub fn with_deferred(mut self, deferred: Vec<String>) -> Self {
        self.deferred = deferred;
        self
    }

    /// Flush deferred SQL (call at the end of a migration).
    pub fn finish(mut self) -> Vec<String> {
        let d = std::mem::take(&mut self.deferred);
        self.sql.0.extend(d);
        self.sql.0
    }

    /// Column type (`field.db_type`).
    pub fn db_type(&self, f: &Field, owner: &ModelMeta) -> Result<String> {
        let v = self.vendor;
        Ok(match f.ty {
            FieldType::Auto => if v == Vendor::Sqlite { "integer" } else { "integer GENERATED BY DEFAULT AS IDENTITY" }.into(),
            FieldType::BigAuto => if v == Vendor::Sqlite { "integer" } else { "bigint GENERATED BY DEFAULT AS IDENTITY" }.into(),
            FieldType::SmallAuto => if v == Vendor::Sqlite { "integer" } else { "smallint GENERATED BY DEFAULT AS IDENTITY" }.into(),
            FieldType::Boolean => if v == Vendor::Sqlite { "bool" } else { "boolean" }.into(),
            FieldType::Char => format!("varchar({})", f.max_length.unwrap_or(255)),
            FieldType::Email => format!("varchar({})", f.max_length.unwrap_or(254)),
            FieldType::Url => format!("varchar({})", f.max_length.unwrap_or(200)),
            FieldType::Slug => format!("varchar({})", f.max_length.unwrap_or(50)),
            FieldType::File | FieldType::Image => format!("varchar({})", f.max_length.unwrap_or(100)),
            FieldType::Text => "text".into(),
            FieldType::Integer | FieldType::PositiveInteger => "integer".into(),
            FieldType::BigInteger | FieldType::PositiveBigInteger => "bigint".into(),
            FieldType::SmallInteger | FieldType::PositiveSmallInteger => "smallint".into(),
            FieldType::Float => if v == Vendor::Sqlite { "real" } else { "double precision" }.into(),
            FieldType::Decimal => {
                if v == Vendor::Sqlite {
                    "decimal".into()
                } else {
                    format!("numeric({}, {})", f.max_digits.unwrap_or(10), f.decimal_places.unwrap_or(2))
                }
            }
            FieldType::Date => "date".into(),
            FieldType::DateTime => if v == Vendor::Sqlite { "datetime" } else { "timestamp with time zone" }.into(),
            FieldType::Time => "time".into(),
            FieldType::Duration => if v == Vendor::Sqlite { "bigint" } else { "interval" }.into(),
            FieldType::Uuid => if v == Vendor::Sqlite { "char(32)" } else { "uuid" }.into(),
            FieldType::Binary => if v == Vendor::Sqlite { "blob" } else { "bytea" }.into(),
            FieldType::Json => if v == Vendor::Sqlite { "text" } else { "jsonb" }.into(),
            FieldType::GenericIpAddress => if v == Vendor::Sqlite { "char(39)" } else { "inet" }.into(),
            FieldType::ForeignKey | FieldType::OneToOne => {
                let target = self.registry.target_of(owner, f)?;
                let rel = f.rel.as_ref().expect("relation");
                let tf = match &rel.to_field {
                    Some(n) => target.get_field(n).cloned().unwrap_or_else(|| target.pk().clone()),
                    None => target.pk().clone(),
                };
                // The FK column mirrors the target type without identity/autoincrement.
                match tf.ty {
                    FieldType::Auto => "integer".into(),
                    FieldType::BigAuto => "bigint".into(),
                    FieldType::SmallAuto => "smallint".into(),
                    _ => self.db_type(&Field { primary_key: false, ..tf }, target)?,
                }
            }
            FieldType::ManyToMany => return Err(Error::field_error("many-to-many fields have no column".to_owned())),
        })
    }

    fn default_sql(&self, f: &Field) -> Option<String> {
        let v = match f.default.as_ref()? {
            Default_::Value(v) => v.clone(),
            Default_::Callable(_) => return None,
        };
        Some(match v {
            Value::Bool(b) => if self.vendor == Vendor::Sqlite { i32::from(b).to_string() } else if b { "true".into() } else { "false".into() },
            Value::Int(i) => i.to_string(),
            Value::Float(f) => f.to_string(),
            Value::Str(s) => format!("'{}'", s.replace('\'', "''")),
            Value::Null => "NULL".into(),
            other => format!("'{}'", crate::models::fields_db::adapt_to_text(&other).replace('\'', "''")),
        })
    }

    /// `column_sql` for CREATE TABLE.
    fn column_def(&mut self, f: &Field, owner: &ModelMeta, table: &str, inline_fk: bool) -> Result<(String, Vec<String>)> {
        let v = self.vendor;
        let mut sql = format!("{} {}", q(v, &f.column()), self.db_type(f, owner)?);
        let mut checks = Vec::new();
        if matches!(f.ty, FieldType::PositiveInteger | FieldType::PositiveBigInteger | FieldType::PositiveSmallInteger) {
            checks.push(format!("{} >= 0", q(v, &f.column())));
        }
        if f.ty == FieldType::Json && v == Vendor::Sqlite {
            checks.push(format!("(JSON_VALID({}) OR {} IS NULL)", q(v, &f.column()), q(v, &f.column())));
        }
        sql.push_str(if f.null { " NULL" } else { " NOT NULL" });
        if f.primary_key {
            sql.push_str(" PRIMARY KEY");
            if v == Vendor::Sqlite && f.ty.is_auto() {
                sql.push_str(" AUTOINCREMENT");
            }
        } else if f.unique {
            sql.push_str(" UNIQUE");
        }
        let _ = table;
        if inline_fk && f.is_relation() && f.rel.as_ref().is_some_and(|r| r.db_constraint) {
            let target = self.registry.target_of(owner, f)?;
            let rel = f.rel.as_ref().expect("relation");
            let tcol = rel.to_field.as_ref().and_then(|n| target.get_field(n)).map_or_else(|| target.pk().column(), Field::column);
            sql.push_str(&format!(" REFERENCES {} ({}) DEFERRABLE INITIALLY DEFERRED", q(v, &target.db_table), q(v, &tcol)));
        }
        let checks: Vec<String> = checks;
        Ok((sql, checks))
    }

    /// `create_model`.
    pub fn create_model(&mut self, m: &ModelMeta) -> Result<()> {
        let v = self.vendor;
        let mut cols = Vec::new();
        let mut checks_sql = Vec::new();
        let mut deferred_fks = Vec::new();
        let mut deferred_indexes = Vec::new();
        for f in m.concrete_fields() {
            let inline = v == Vendor::Sqlite;
            let (def, checks) = self.column_def(f, m, &m.db_table, inline)?;
            cols.push(def);
            for c in checks {
                checks_sql.push((f.column(), c));
            }
            if v == Vendor::Postgresql && f.is_relation() && f.rel.as_ref().is_some_and(|r| r.db_constraint) {
                let target = self.registry.target_of(m, f)?;
                let rel = f.rel.as_ref().expect("relation");
                let tcol = rel.to_field.as_ref().and_then(|n| target.get_field(n)).map_or_else(|| target.pk().column(), Field::column);
                let fk_name = fk_constraint_name(v, &m.db_table, &f.column(), &target.db_table, &tcol);
                deferred_fks.push(format!(
                    "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}) DEFERRABLE INITIALLY DEFERRED",
                    q(v, &m.db_table),
                    q(v, &fk_name),
                    q(v, &f.column()),
                    q(v, &target.db_table),
                    q(v, &tcol)
                ));
            }
            if f.db_index && !f.unique && !f.primary_key {
                deferred_indexes.push(self.create_index_sql(&m.db_table, &[&f.column()], &index_name(v, &m.db_table, &[&f.column()], ""), false, f.ty.is_string() && v == Vendor::Postgresql));
                if v == Vendor::Postgresql && matches!(f.ty, FieldType::Char | FieldType::Text | FieldType::Email | FieldType::Url | FieldType::Slug) {
                    deferred_indexes.push(format!(
                        "CREATE INDEX {} ON {} ({} varchar_pattern_ops)",
                        q(v, &index_name(v, &m.db_table, &[&f.column()], "_like")),
                        q(v, &m.db_table),
                        q(v, &f.column())
                    ));
                }
            }
        }
        let mut table_parts = cols;
        for (_col, c) in checks_sql {
            table_parts.push(format!("CHECK ({c})"));
        }
        let mut deferred_uniques = Vec::new();
        for group in &m.unique_together {
            let cols: Vec<String> = group.iter().filter_map(|n| m.get_field(n)).map(Field::column).collect();
            let refs: Vec<&str> = cols.iter().map(String::as_str).collect();
            let name = index_name(v, &m.db_table, &refs, "_uniq");
            deferred_uniques.push(if v == Vendor::Sqlite {
                format!("CREATE UNIQUE INDEX {} ON {} ({})", q(v, &name), q(v, &m.db_table), refs.iter().map(|c| q(v, c)).collect::<Vec<_>>().join(", "))
            } else {
                format!("ALTER TABLE {} ADD CONSTRAINT {} UNIQUE ({})", q(v, &m.db_table), q(v, &name), refs.iter().map(|c| q(v, c)).collect::<Vec<_>>().join(", "))
            });
        }
        for c in &m.constraints {
            if let Constraint::Unique { name, fields, .. } = c {
                let cols: Vec<String> = fields.iter().filter_map(|n| m.get_field(n)).map(|f| q(v, &f.column())).collect();
                table_parts.push(format!("CONSTRAINT {} UNIQUE ({})", q(v, name), cols.join(", ")));
            }
        }
        self.emit(format!("CREATE TABLE {} ({})", q(v, &m.db_table), table_parts.join(", ")));
        self.deferred.extend(deferred_fks);
        self.deferred.extend(deferred_uniques);
        self.deferred.extend(deferred_indexes);
        for idx in &m.indexes {
            let cols: Vec<String> = idx.fields.iter().map(|f| m.get_field(f.trim_start_matches('-')).map(Field::column).unwrap_or_default()).collect();
            let refs: Vec<&str> = cols.iter().map(String::as_str).collect();
            let name = idx.name.clone().unwrap_or_else(|| index_name(v, &m.db_table, &refs, "_idx"));
            let sql = self.create_index_sql(&m.db_table, &refs, &name, false, false);
            self.deferred.push(sql);
        }
        // Auto-created M2M tables.
        for f in m.many_to_many() {
            if f.rel.as_ref().is_some_and(|r| r.through.is_none()) {
                let through = self.registry.through_of(m, f)?.clone();
                self.create_model(&through)?;
            }
        }
        Ok(())
    }

    fn create_index_sql(&self, table: &str, cols: &[&str], name: &str, unique: bool, _pattern: bool) -> String {
        let v = self.vendor;
        format!(
            "CREATE {}INDEX {} ON {} ({})",
            if unique { "UNIQUE " } else { "" },
            q(v, name),
            q(v, table),
            cols.iter().map(|c| q(v, c)).collect::<Vec<_>>().join(", ")
        )
    }

    /// `delete_model`.
    pub fn delete_model(&mut self, m: &ModelMeta) -> Result<()> {
        let v = self.vendor;
        for f in m.many_to_many() {
            if f.rel.as_ref().is_some_and(|r| r.through.is_none()) {
                let t = self.registry.through_of(m, f)?.clone();
                self.delete_model(&t)?;
            }
        }
        self.emit(format!("DROP TABLE {}{}", q(v, &m.db_table), if v == Vendor::Postgresql { " CASCADE" } else { "" }));
        Ok(())
    }

    /// `add_field`.
    pub fn add_field(&mut self, m: &ModelMeta, f: &Field) -> Result<()> {
        let v = self.vendor;
        if f.many_to_many_() {
            if f.rel.as_ref().is_some_and(|r| r.through.is_none()) {
                let through = self.registry.through_of(m, f)?.clone();
                self.create_model(&through)?;
            }
            return Ok(());
        }
        let inline = v == Vendor::Sqlite;
        let (mut def, checks) = self.column_def(f, m, &m.db_table, inline)?;
        if !f.null && !f.primary_key {
            if let Some(d) = self.default_sql(f) {
                def = def.replace(" NOT NULL", &format!(" DEFAULT {d} NOT NULL"));
            }
        }
        let mut sql = format!("ALTER TABLE {} ADD COLUMN {def}", q(v, &m.db_table));
        for c in checks {
            sql.push_str(&format!(" CHECK ({c})"));
        }
        self.emit(sql);
        if v == Vendor::Postgresql && f.is_relation() && f.rel.as_ref().is_some_and(|r| r.db_constraint) {
            let target = self.registry.target_of(m, f)?;
            let tcol = target.pk().column();
            let name = fk_constraint_name(v, &m.db_table, &f.column(), &target.db_table, &tcol);
            self.deferred.push(format!(
                "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({}) DEFERRABLE INITIALLY DEFERRED",
                q(v, &m.db_table),
                q(v, &name),
                q(v, &f.column()),
                q(v, &target.db_table),
                q(v, &tcol)
            ));
        }
        if f.db_index && !f.unique {
            let name = index_name(v, &m.db_table, &[&f.column()], "");
            self.deferred.push(self.create_index_sql(&m.db_table, &[&f.column()], &name, false, false));
        }
        Ok(())
    }

    /// `remove_field`.
    pub fn remove_field(&mut self, m: &ModelMeta, f: &Field) -> Result<()> {
        let v = self.vendor;
        if f.many_to_many_() {
            if f.rel.as_ref().is_some_and(|r| r.through.is_none()) {
                let t = self.registry.through_of(m, f)?.clone();
                self.delete_model(&t)?;
            }
            return Ok(());
        }
        self.emit(format!("ALTER TABLE {} DROP COLUMN {}{}", q(v, &m.db_table), q(v, &f.column()), if v == Vendor::Postgresql { " CASCADE" } else { "" }));
        Ok(())
    }

    /// `alter_field` (PostgreSQL `ALTER COLUMN`; SQLite rebuilds the table).
    pub fn alter_field(&mut self, m: &ModelMeta, old: &Field, new: &Field) -> Result<()> {
        let v = self.vendor;
        if v == Vendor::Postgresql {
            let t = q(v, &m.db_table);
            let col = q(v, &new.column());
            if old.column() != new.column() {
                self.emit(format!("ALTER TABLE {t} RENAME COLUMN {} TO {col}", q(v, &old.column())));
            }
            let new_type = self.db_type(new, m)?;
            if self.db_type(old, m)? != new_type {
                self.emit(format!("ALTER TABLE {t} ALTER COLUMN {col} TYPE {} USING {col}::{}", new_type.split(" GENERATED").next().unwrap_or(&new_type), new_type.split(" GENERATED").next().unwrap_or(&new_type)));
            }
            if old.null != new.null {
                self.emit(format!("ALTER TABLE {t} ALTER COLUMN {col} {} NOT NULL", if new.null { "DROP" } else { "SET" }));
            }
            if old.unique != new.unique {
                if new.unique {
                    self.emit(format!("ALTER TABLE {t} ADD CONSTRAINT {} UNIQUE ({col})", q(v, &format!("{}_{}_{}_uniq", m.db_table, new.column(), names_digest(&[&m.db_table, &new.column()], 8)))));
                } else {
                    self.emit(format!("ALTER TABLE {t} DROP CONSTRAINT {}", q(v, &format!("{}_{}_key", m.db_table, new.column()))));
                }
            }
            return Ok(());
        }
        // SQLite: remake the table with the new definition.
        self.remake_table_sqlite(m, Some((old, new)))
    }

    fn remake_table_sqlite(&mut self, m: &ModelMeta, change: Option<(&Field, &Field)>) -> Result<()> {
        let v = self.vendor;
        let new_table = format!("new__{}", m.db_table);
        let mut tmp = m.clone();
        tmp.db_table = new_table.clone();
        if let Some((old, new)) = change {
            for f in &mut tmp.fields {
                if f.name == old.name {
                    *f = new.clone();
                }
            }
        }
        let saved = self.sql.0.len();
        let deferred = self.deferred.len();
        self.create_model(&tmp)?;
        let create: Vec<String> = self.sql.0.split_off(saved);
        self.deferred.truncate(deferred);
        let (old_cols, new_cols): (Vec<String>, Vec<String>) = m
            .concrete_fields()
            .filter(|f| change.is_none_or(|(_, n)| n.name != f.name || true))
            .map(|f| {
                let new_col = change.filter(|(o, _)| o.name == f.name).map_or_else(|| f.column(), |(_, n)| n.column());
                (q(v, &f.column()), q(v, &new_col))
            })
            .unzip();
        for c in create.into_iter().take(1) {
            self.emit(c);
        }
        self.emit(format!(
            "INSERT INTO {} ({}) SELECT {} FROM {}",
            q(v, &new_table),
            new_cols.join(", "),
            old_cols.join(", "),
            q(v, &m.db_table)
        ));
        self.emit(format!("DROP TABLE {}", q(v, &m.db_table)));
        self.emit(format!("ALTER TABLE {} RENAME TO {}", q(v, &new_table), q(v, &m.db_table)));
        Ok(())
    }

    /// `alter_db_table` / `RenameModel`.
    pub fn rename_table(&mut self, old: &str, new: &str) {
        let v = self.vendor;
        self.emit(format!("ALTER TABLE {} RENAME TO {}", q(v, old), q(v, new)));
    }

    /// `RenameField`.
    pub fn rename_column(&mut self, table: &str, old: &str, new: &str) {
        let v = self.vendor;
        self.emit(format!("ALTER TABLE {} RENAME COLUMN {} TO {}", q(v, table), q(v, old), q(v, new)));
    }

    /// `AddIndex`.
    pub fn add_index(&mut self, m: &ModelMeta, idx: &crate::models::meta::Index) {
        let v = self.vendor;
        let cols: Vec<String> = idx.fields.iter().map(|f| q(v, &m.get_field(f.trim_start_matches('-')).map(Field::column).unwrap_or_default())).collect();
        let raw: Vec<String> = idx.fields.iter().map(|f| m.get_field(f.trim_start_matches('-')).map(Field::column).unwrap_or_default()).collect();
        let refs: Vec<&str> = raw.iter().map(String::as_str).collect();
        let name = idx.name.clone().unwrap_or_else(|| index_name(v, &m.db_table, &refs, "_idx"));
        self.emit(format!("CREATE INDEX {} ON {} ({})", q(v, &name), q(v, &m.db_table), cols.join(", ")));
    }

    /// `RemoveIndex`.
    pub fn remove_index(&mut self, name: &str) {
        let v = self.vendor;
        self.emit(format!("DROP INDEX {}", q(v, name)));
    }

    /// `AlterUniqueTogether`: add the new groups (removal needs the constraint name; SQLite remakes).
    pub fn alter_unique_together(&mut self, m: &ModelMeta, old: &[Vec<String>], new: &[Vec<String>]) -> Result<()> {
        let v = self.vendor;
        for g in new.iter().filter(|g| !old.contains(g)) {
            let cols: Vec<String> = g.iter().filter_map(|n| m.get_field(n)).map(Field::column).collect();
            let refs: Vec<&str> = cols.iter().map(String::as_str).collect();
            let name = index_name(v, &m.db_table, &refs, "_uniq");
            if v == Vendor::Sqlite {
                self.emit(format!("CREATE UNIQUE INDEX {} ON {} ({})", q(v, &name), q(v, &m.db_table), cols.iter().map(|c| q(v, c)).collect::<Vec<_>>().join(", ")));
            } else {
                self.emit(format!("ALTER TABLE {} ADD CONSTRAINT {} UNIQUE ({})", q(v, &m.db_table), q(v, &name), cols.iter().map(|c| q(v, c)).collect::<Vec<_>>().join(", ")));
            }
        }
        for g in old.iter().filter(|g| !new.contains(g)) {
            let cols: Vec<String> = g.iter().filter_map(|n| m.get_field(n)).map(Field::column).collect();
            let refs: Vec<&str> = cols.iter().map(String::as_str).collect();
            let name = index_name(v, &m.db_table, &refs, "_uniq");
            if v == Vendor::Sqlite {
                self.emit(format!("DROP INDEX {}", q(v, &name)));
            } else {
                self.emit(format!("ALTER TABLE {} DROP CONSTRAINT {}", q(v, &m.db_table), q(v, &name)));
            }
        }
        Ok(())
    }
}

/// `_create_fk_sql` constraint name: `<table>_<col>_<hash>_fk_<reftable>_<refcol>`.
fn fk_constraint_name(v: Vendor, table: &str, col: &str, ref_table: &str, ref_col: &str) -> String {
    let suffix = format!("_fk_{ref_table}_{ref_col}");
    index_name(v, table, &[col], &suffix)
}
