use crate::models::meta::registry;

fn installed_labels() -> Vec<String> {
    apps().map(|a| a.get_app_configs().map(|c| c.label.clone()).collect()).unwrap_or_default()
}

fn migrations_dir(app: &str) -> Result<PathBuf, CommandError> {
    for base in [PathBuf::from("src").join(app), PathBuf::from(app)] {
        if base.is_dir() {
            return Ok(base.join("migrations"));
        }
    }
    Err(CommandError::new(format!("Can't find the source directory of app '{app}' (looked in src/{app} and ./{app}).")))
}

fn number_of(name: &str) -> u32 {
    name.split('_').next().and_then(|n| n.parse().ok()).unwrap_or(0)
}

#[derive(Default)]
pub struct MakeMigrations;

#[async_trait]
impl Command for MakeMigrations {
    fn help(&self) -> &str {
        "Creates new migration(s) for apps."
    }

    fn add_arguments(&self, cmd: clap::Command) -> clap::Command {
        cmd.arg(Arg::new("app_label").num_args(0..))
            .arg(Arg::new("dry_run").long("dry-run").action(ArgAction::SetTrue).help("Just show what migrations would be made; don't actually write them."))
            .arg(Arg::new("name").short('n').long("name").help("Use this name for migration file(s)."))
            .arg(Arg::new("check").long("check").action(ArgAction::SetTrue).help("Exit with a non-zero status if model changes are missing migrations."))
    }

    async fn handle(&self, ctx: &CommandContext, args: &clap::ArgMatches) -> Result<Option<String>, CommandError> {
        let labels = installed_labels();
        let wanted: Vec<String> = args.get_many::<String>("app_label").map(|v| v.cloned().collect()).unwrap_or_default();
        for w in &wanted {
            if !labels.contains(w) {
                return Err(CommandError::new(format!("App '{w}' could not be found. Is it in INSTALLED_APPS?")));
            }
        }
        let loader = MigrationLoader::load(Some(&labels))?;
        let from = loader.full_state()?;
        let to = ProjectState::from_registry(&registry(), Some(&labels));
        let found = changes(&from, &to).map_err(|e| CommandError::new(e.to_string()))?;
        let found: Vec<_> = found.into_iter().filter(|(a, _)| wanted.is_empty() || wanted.contains(a)).collect();
        if found.is_empty() {
            ctx.stdout.write("No changes detected");
            return Ok(None);
        }
        if args.get_flag("check") {
            return Err(CommandError { message: String::new(), returncode: 1, is_system_check: false });
        }
        let dry = args.get_flag("dry_run");
        for (app, ops) in found {
            let leaf = loader.leaf(&app);
            let number = leaf.as_ref().map_or(0, |k| number_of(&k.1)) + 1;
            let initial = leaf.is_none();
            let slug = args.get_one::<String>("name").cloned().unwrap_or_else(|| suggest_name(&ops, initial));
            let name = format!("{number:04}_{slug}");
            let mut deps: Vec<(String, String)> = leaf.into_iter().collect();
            for other in referenced_apps(&ops, &app) {
                let dep = loader.leaf(&other).map_or_else(|| "0001_initial".to_owned(), |k| k.1);
                deps.push((other, dep));
            }
            let module = format!("m{name}");
            let path = migrations_dir(&app)?;
            ctx.stdout.write(&ctx.style.migrate_heading(&format!("Migrations for '{app}':")));
            ctx.stdout.write(&format!("  {}", path.join(format!("{module}.rs")).display()));
            for op in &ops {
                ctx.stdout.write(&format!("    + {}", op.describe()));
            }
            if dry {
                continue;
            }
            fs::create_dir_all(&path).map_err(|e| CommandError::new(e.to_string()))?;
            fs::write(path.join(format!("{module}.rs")), migration_source(&app, &name, initial, &deps, &ops)).map_err(|e| CommandError::new(e.to_string()))?;
            let modrs = path.join("mod.rs");
            let mut text = fs::read_to_string(&modrs).unwrap_or_else(|_| format!("//! Migrations for the {app} app (generated by `makemigrations`).\n"));
            let decl = format!("pub mod {module};");
            if !text.lines().any(|l| l.trim() == decl) {
                if !text.ends_with('\n') {
                    text.push('\n');
                }
                text.push_str(&decl);
                text.push('\n');
            }
            fs::write(&modrs, text).map_err(|e| CommandError::new(e.to_string()))?;
        }
        if !dry {
            ctx.stdout.write("Rebuild the project (cargo build) for the new migration to be picked up.");
        }
        Ok(None)
    }
}

#[derive(Default)]
pub struct Migrate;

#[async_trait]
impl Command for Migrate {
    fn help(&self) -> &str {
        "Updates database schema. Manages both apps with migrations and those without."
    }

    fn add_arguments(&self, cmd: clap::Command) -> clap::Command {
        cmd.arg(Arg::new("app_label").help("App label of an application to synchronize the state."))
            .arg(Arg::new("migration_name").help("Database state will be brought to the state after that migration. Use the name \"zero\" to unapply all migrations."))
            .arg(Arg::new("database").long("database").default_value("default").help("Nominates a database to synchronize."))
            .arg(Arg::new("noinput").long("noinput").visible_alias("no-input").action(ArgAction::SetTrue))
    }

    async fn handle(&self, ctx: &CommandContext, args: &clap::ArgMatches) -> Result<Option<String>, CommandError> {
        let db = Db::using(args.get_one::<String>("database").map_or("default", String::as_str));
        let labels = installed_labels();
        let loader = MigrationLoader::load(Some(&labels))?;
        let target = match (args.get_one::<String>("app_label"), args.get_one::<String>("migration_name")) {
            (Some(a), Some(n)) => Target::Migration(a.clone(), n.clone()),
            (Some(a), None) => Target::App(a.clone()),
            _ => Target::All,
        };
        if ctx.verbosity >= 1 {
            ctx.stdout.write(&ctx.style.migrate_heading("Operations to perform:"));
            let mut with: Vec<String> = loader.migrations.keys().map(|k| k.0.clone()).collect();
            with.sort();
            with.dedup();
            ctx.stdout.write(&format!("  Apply all migrations: {}", with.join(", ")));
            ctx.stdout.write(&ctx.style.migrate_heading("Running migrations:"));
        }
        for line in migrate(&db, &loader, &target).await? {
            if ctx.verbosity >= 1 {
                ctx.stdout.write(&line);
            }
        }
        Ok(None)
    }
}

#[derive(Default)]
pub struct ShowMigrations;

#[async_trait]
impl Command for ShowMigrations {
    fn help(&self) -> &str {
        "Shows all available migrations for the current project."
    }

    fn add_arguments(&self, cmd: clap::Command) -> clap::Command {
        cmd.arg(Arg::new("app_label").num_args(0..)).arg(Arg::new("database").long("database").default_value("default"))
    }

    async fn handle(&self, ctx: &CommandContext, args: &clap::ArgMatches) -> Result<Option<String>, CommandError> {
        let db = Db::using(args.get_one::<String>("database").map_or("default", String::as_str));
        let labels = installed_labels();
        let loader = MigrationLoader::load(Some(&labels))?;
        let done = applied(&db).await?;
        let wanted: Vec<String> = args.get_many::<String>("app_label").map(|v| v.cloned().collect()).unwrap_or_default();
        let mut app_names: Vec<String> = loader.migrations.keys().map(|k| k.0.clone()).collect();
        app_names.sort();
        app_names.dedup();
        for app in app_names.into_iter().filter(|a| wanted.is_empty() || wanted.contains(a)) {
            ctx.stdout.write(&ctx.style.migrate_label(&app));
            for k in loader.order.iter().filter(|k| k.0 == app) {
                ctx.stdout.write(&format!(" [{}] {}", if done.contains(k) { "X" } else { " " }, k.1));
            }
        }
        Ok(None)
    }
}

#[derive(Default)]
pub struct SqlMigrate;

#[async_trait]
impl Command for SqlMigrate {
    fn help(&self) -> &str {
        "Prints the SQL statements for the named migration."
    }

    fn add_arguments(&self, cmd: clap::Command) -> clap::Command {
        cmd.arg(Arg::new("app_label").required(true))
            .arg(Arg::new("migration_name").required(true))
            .arg(Arg::new("database").long("database").default_value("default"))
            .arg(Arg::new("backwards").long("backwards").action(ArgAction::SetTrue))
    }

    async fn handle(&self, _ctx: &CommandContext, args: &clap::ArgMatches) -> Result<Option<String>, CommandError> {
        let (app, name) = (args.get_one::<String>("app_label").expect("required"), args.get_one::<String>("migration_name").expect("required"));
        let db = Db::using(args.get_one::<String>("database").map_or("default", String::as_str));
        let loader = MigrationLoader::load(None)?;
        let key = loader
            .order
            .iter()
            .find(|k| k.0 == *app && k.1.starts_with(name.as_str()))
            .cloned()
            .ok_or_else(|| CommandError::new(format!("Cannot find a migration matching '{name}' from app '{app}'.")))?;
        let backwards = args.get_flag("backwards");
        let statements = migration_sql(&loader, &key, db.vendor(), backwards)?;
        let mut out = String::from("BEGIN;\n");
        for op in &loader.migrations[&key].operations {
            out.push_str(&format!("--\n-- {}\n--\n", op.describe()));
        }
        for s in statements {
            out.push_str(&s);
            out.push_str(";\n");
        }
        out.push_str("COMMIT;");
        Ok(Some(out))
    }
}

