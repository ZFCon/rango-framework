//! Shared test models (what `#[derive(Model)]` will generate) and database setup.
#![allow(dead_code)]

use chrono::{DateTime, Utc};
use rango_core::conf::{DatabaseConfig, Settings};

use rango_db::models::{ForeignKey, ManyToMany, Model};

#[derive(Clone, Debug, PartialEq, Model)]
#[model(crate = "rango_db", app_label = "polls")]
pub struct Question {
    #[field(primary_key, auto)]
    pub id: Option<i64>,
    #[field(max_length = 200)]
    pub question_text: String,
    #[field(verbose_name = "date published")]
    pub pub_date: DateTime<Utc>,
}

#[derive(Clone, Debug, PartialEq, Model)]
#[model(crate = "rango_db", app_label = "polls")]
pub struct Choice {
    #[field(primary_key, auto)]
    pub id: Option<i64>,
    pub question: ForeignKey<Question>,
    #[field(max_length = 200)]
    pub choice_text: String,
    #[field(default = 0)]
    pub votes: i32,
}

#[derive(Clone, Debug, PartialEq, Model)]
#[model(crate = "rango_db", app_label = "polls")]
pub struct Author {
    #[field(primary_key, auto)]
    pub id: Option<i64>,
    #[field(max_length = 100)]
    pub name: String,
    pub age: Option<i32>,
}

#[derive(Clone, Debug, PartialEq, Model)]
#[model(crate = "rango_db", app_label = "polls")]
pub struct Book {
    #[field(primary_key, auto)]
    pub id: Option<i64>,
    #[field(max_length = 200)]
    pub title: String,
    pub authors: ManyToMany<Author>,
    pub published: chrono::NaiveDate,
    #[field(max_digits = 6, decimal_places = 2)]
    pub price: rust_decimal::Decimal,
}

pub fn register_models() {}

pub fn settings_for(db: DatabaseConfig) -> Settings {
    Settings {
        secret_key: "k".into(),
        use_tz: true,
        time_zone: "UTC".into(),
        databases: std::collections::BTreeMap::from([("default".to_owned(), db)]),
        ..Settings::default()
    }
}

/// DDL for SQLite (what `migrate` will generate in M4).
pub const SQLITE_DDL: &str = r#"
CREATE TABLE "polls_question" ("id" integer NOT NULL PRIMARY KEY AUTOINCREMENT, "question_text" varchar(200) NOT NULL, "pub_date" datetime NOT NULL);
CREATE TABLE "polls_choice" ("id" integer NOT NULL PRIMARY KEY AUTOINCREMENT, "choice_text" varchar(200) NOT NULL, "votes" integer NOT NULL, "question_id" bigint NOT NULL REFERENCES "polls_question" ("id") DEFERRABLE INITIALLY DEFERRED);
CREATE TABLE "polls_author" ("id" integer NOT NULL PRIMARY KEY AUTOINCREMENT, "name" varchar(100) NOT NULL, "age" integer NULL);
CREATE TABLE "polls_book" ("id" integer NOT NULL PRIMARY KEY AUTOINCREMENT, "title" varchar(200) NOT NULL, "published" date NOT NULL, "price" decimal NOT NULL);
CREATE TABLE "polls_book_authors" ("id" integer NOT NULL PRIMARY KEY AUTOINCREMENT, "book_id" bigint NOT NULL REFERENCES "polls_book" ("id") DEFERRABLE INITIALLY DEFERRED, "author_id" bigint NOT NULL REFERENCES "polls_author" ("id") DEFERRABLE INITIALLY DEFERRED);
CREATE UNIQUE INDEX "polls_book_authors_book_id_author_id_uniq" ON "polls_book_authors" ("book_id", "author_id");
"#;

