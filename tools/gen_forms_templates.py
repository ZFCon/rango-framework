#!/usr/bin/env python3
"""Regenerate crates/rango-forms/src/templates_data.rs from crates/rango-forms/templates/ (the built-in form templates)."""
import os
root = os.path.join(os.path.dirname(__file__), "..", "crates", "rango-forms")
files = sorted(os.path.relpath(os.path.join(d, f), os.path.join(root, "templates")) for d, _, fs in os.walk(os.path.join(root, "templates")) for f in fs)
with open(os.path.join(root, "src", "templates_data.rs"), "w") as out:
    out.write("//! Generated by tools/gen_forms_templates.py; built-in form templates (see NOTICE).\n\n")
    out.write("pub const TEMPLATES: &[(&str, &str)] = &[\n")
    for f in files:
        out.write(f'    ("{f}", include_str!("../templates/{f}")),\n')
    out.write("];\n")
